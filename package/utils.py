def commits_to_issues():
    """
    Counts the number of commits that have 1, 2, 3,...., n linked issues
    """

    from db import init_db, SEOSS33
    projects = init_db()
    counts = {}
    for project in projects:
        db = SEOSS33(project)
        links = db.get_trace_links()

        for _, issues in links:
            counts.setdefault(len(issues), 0) 
            counts[len(issues)] += 1
        db.close()

    print(f"No. of issues | commits")
    for length, count in sorted(counts.items(), key=lambda x:x[0]):
        print(f"{length:>13} | {count:<7}")