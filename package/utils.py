    plt.show()

    fig, axs = plt.subplots(6, 6, figsize=(18, 18))
    for i, (project, _) in enumerate(precisions.items()):
        row = i // 6
        col = i % 6
        plot_retrievers(axs[row][col], precisions[project], title=project, xlabel="K", ylabel="Precision")
    plt.show()

