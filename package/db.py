class Issue:
    def __init__(self, issue_id, issue_summary, issue_description):
        self.id = issue_id
        self.summary = issue_summary or ""
        self.description = issue_description or ""

    def to_text(self):
        return f"{self.summary}. {self.description}".strip()

    def __eq__(self, other):
        if isinstance(other, Issue):
            return self.id == other.id
        return False

    def __hash__(self):
        return hash(self.id)
    
    def __repr__(self):
        return self.to_text()

class Commit:
    def __init__(self, hash, message):
        self.hash = hash
        self.message = message

    def __eq__(self, other):
        if isinstance(other, Commit):
            return self.hash == other.hash
        return False

    def __hash__(self):
        return hash(self.hash)
    
    def __repr__(self):
        return f"{self.message}"

